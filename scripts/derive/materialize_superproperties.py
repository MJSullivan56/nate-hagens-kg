#!/usr/bin/env python3
"""Materialize sub-property entailments into data/inferred/, never data/seed/.

For every rdfs:subPropertyOf declared in data/seed/ (followed transitively,
e.g. thinkr:challenges -> thinkr:contrastsWith -> thinkr:relatesTo), write
the implied super-property triple when the seed does not already state it:
thinkr:hasHost implies dct:creator, thinkr:hasGuest implies dct:contributor,
thinkr:hasCanonicalSource implies dct:source, and so on.

Output is one generated file, regenerated in full on each run. The JSON-LD
exporter loads data/seed/ plus this file. Run compute_inverses.py first so
mirrored symmetric links (e.g. both directions of thinkr:complements) get
their super-property triples too.

Usage:
    python scripts/derive/materialize_superproperties.py            # write
    python scripts/derive/materialize_superproperties.py --dry-run
    python scripts/derive/materialize_superproperties.py --check    # CI
"""
import argparse, collections, sys
from pathlib import Path
import rdflib
from rdflib.namespace import RDFS

SEED = Path("data/seed")
OUT = Path("data/inferred/subproperty-closure.ttl")
EXCLUDE = {"merged_for_protege.ttl", "scratch.ttl"}
HEADER = """# GENERATED by scripts/derive/materialize_superproperties.py. Do not edit by hand.
# Super-property triples implied by rdfs:subPropertyOf declarations in data/seed/.
# Regenerate after any seed change (after compute_inverses.py).
"""

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    g = rdflib.Graph()
    for p in sorted(SEED.glob("*.ttl")):
        if p.name not in EXCLUDE:
            g.parse(p)
    sup = collections.defaultdict(set)
    for a, b in g.subject_objects(RDFS.subPropertyOf):
        sup[a].add(b)
    def closure(p, seen=None):
        seen = seen or set()
        for b in sup.get(p, ()):
            if b not in seen:
                seen.add(b); closure(b, seen)
        return seen

    out = rdflib.Graph()
    for pre, ns in g.namespaces():
        out.bind(pre, ns)
    counts = collections.Counter()
    for sub in list(sup):
        for s, o in g.subject_objects(sub):
            for b in closure(sub):
                if (s, b, o) not in g:
                    out.add((s, b, o)); counts[(g.qname(sub), g.qname(b))] += 1
    print(f"Inferred super-property triples: {len(out)}")
    for (a, b), n in counts.most_common(): print(f"  {a} -> {b}: {n}")

    new = HEADER + "\n" + out.serialize(format="turtle")
    old = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    if args.check:
        if new != old:
            print(f"STALE: {OUT} needs regenerating"); sys.exit(1)
        print("OK"); return
    if args.dry_run:
        print(f"(dry run) {'would update' if new != old else 'no change to'} {OUT}"); return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(new, encoding="utf-8")
    print(f"Wrote {OUT}")

if __name__ == "__main__":
    main()

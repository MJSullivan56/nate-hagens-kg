"""
Stage 2 evaluation harness for the bio-intro extraction pipeline.

Tests whether an LLM can extract institutional-affiliation facts from a
Stage-1 intro segment (extraction/segment_intros.py's output), checked
against hand-verified gold data for exactly 2 real files: Josh Farley
(TGS_07) and Malin Pinsky (TGS_179).

SCHEMA HISTORY (2026-07-15): the original schema minted `thinkr:Human`
directly with a flat `thinkr:memberOf` property. Corrected after review
against a real Relationship individual (Relationship.JoshFarley_
UniversityOfVermont, hasSubject: Persona.JoshFarley, not Human) — this
project's Persona-centered architecture (CLAUDE.md decision 0f) routes
every relationship except actsThrough through Persona, never Human.
Corrected further after a second, deeper realization: a podcast intro is
structurally a Persona-generating source, not a Human-verifying one — it
reliably states public role/affiliation, never reliably a guest's actual
legal name or other private biography (the "Nathan" in Human.NathanHagens
came from his own X handle, never from anything TGS itself said). The
Human/Persona split is also genuinely blurry, not just under-sourced, and
gets HARDER for less-famous guests, not easier — a university faculty
bio is simultaneously Persona content (public professional role) and
genuine Human content (an earned degree), with no mechanical rule
separating the two readings. See docs/sidecar-cleanup-handoff.md's
2026-07-15 "STAGE 2 SCHEMA DESIGN" entry for the full reasoning.

RESULT: Stage 2 mints ONLY thinkr:Persona from the transcript. Any
bio-shaped details the intro surfaces (credentials, career history) go
into a `human_lead` scopeNote, explicitly flagged as unverified candidate
Human facts for a SEPARATE Pass 2 (not built here) that does real web
verification — the same discipline as this project's existing bootstrap
procedure (CLAUDE.md), staying alert to the "Cher trap": a found
"personal website" may itself just be more Persona surface.

CONFIRMED BY A REAL DATA CHECK, not assumed: this eval's own two test
files already span the two downstream cases the schema has to handle —
Human.JoshFarley / Persona.JoshFarley both already exist in the graph
(grep-confirmed); Malin Pinsky has zero hits anywhere. Whether a given
extraction represents a brand-new mint or an addition to an existing
Persona is treated here as a SEPARATE reconciliation step (name-matching
against personas.ttl) — deliberately kept out of the extraction prompt
itself, which stays scoped to "pull the facts out of this text."

DELIBERATELY NARROW SCOPE, unchanged from the first version: this only
tests the institutional-relationship slice of the schema. It does NOT
test relationship-signal extraction ("my friend", "PhD chair") or
explicit concept-connections (the Superorganism/Lustig pattern) — those
need their own gold data and their own evaluation pass.

GOLD DATA PROVENANCE: read directly from the Stage-1 intro segments by a
human (this session), not generated by an LLM and not independently
web-verified — the relationships below are exactly what each transcript's
own intro segment states, nothing more. Evaluated here for extraction
fidelity, not for whether the claim itself is independently true.

MODEL NOTE (2026-07-15): claude-opus-4-8 and claude-sonnet-5 both REJECT
a non-default `temperature` (400 error) — a real conflict with "use
temperature for deterministic extraction" if the accurate-model path is
selected. claude-haiku-4-5 still accepts it. Default model is Haiku 4.5
for exactly this reason (plus it's the right tier for a ~1,000-word
structured-extraction task); --model claude-opus-4-8 is supported for
accuracy comparison, with temperature silently omitted for it rather
than sent and 400'd.

Usage:
    python extraction/eval_stage2_yaml.py
    python extraction/eval_stage2_yaml.py --model claude-opus-4-8
"""

import argparse
import os
import re
import sys
from pathlib import Path

import yaml
from anthropic import Anthropic

MODEL_FAST = "claude-haiku-4-5"
MODEL_ACCURATE = "claude-opus-4-8"
MODELS_REJECTING_TEMPERATURE = {MODEL_ACCURATE, "claude-sonnet-5"}

INTRO_SEGMENTS_DIR = Path("extraction/intro_segments")

SYSTEM_PROMPT = """You extract structured facts about a podcast guest from the \
introduction segment of a podcast episode transcript. The host is introducing \
the guest.

IMPORTANT — extract ONLY Persona-level (public role) facts, never Human-level \
(private biography) facts. A podcast intro reliably states a guest's public \
role and institutional affiliations; it does NOT reliably state their actual \
legal name, birthdate, or other private biographical facts, even when it \
sounds confident. Do not assert anything as settled personal biography.

Extract:
1. The guest's publicly-known name (however the host addresses/introduces them).
2. Institutional/organizational relationships the host states directly about \
the guest — memberships, positions, fellowships, affiliations with named \
organizations or academic institutions. Do NOT extract relationship facts \
between the host and guest (e.g. "my friend"), and do NOT extract facts about \
people other than the guest.
3. Any other bio-shaped detail the intro surfaces (credentials, career \
history, degrees, past roles) that is NOT an institutional relationship — \
capture this as an unverified lead, not a fact.

Output ONLY valid YAML, no markdown code fences, no commentary, in exactly \
this shape:

persona:
  target_class: thinkr:Persona
  public_name: <name as publicly known/addressed by the host>
  relationships:
    - property: thinkr:hasPersonalRelationship
      hasObject_name: <organization or institution name, verbatim>
      hasObject_type: thinkr:AcademicInstitution or thinkr:Organization
      hasRelationshipType: thinkr:RelationshipType.Academic (for AcademicInstitution) or thinkr:RelationshipType.Professional (for Organization)
      role_or_position: <title/role, if stated>
      department: <department, only if stated and hasObject_type is AcademicInstitution>

human_lead:
  scopeNote: |
    <any bio-shaped details from the segment that are NOT institutional
    relationships — credentials, career history, degrees — written as
    candidate leads for a later verification pass, not asserted facts.
    If none, write "No additional bio-shaped details stated.">

provenance:
  source_episode: <leave as "UNKNOWN" - not derivable from the segment text alone>
  quoted_evidence: |
    <the exact sentence(s) from the segment that state the relationships above>

If zero relationships are stated, return relationships: [] (empty list). \
Omit the department field entirely on any relationship where it doesn't apply \
(don't write department: null)."""

# Gold data — hand-verified by reading each intro segment directly (this
# session, 2026-07-15). "relationships" here is the set actually checked;
# order doesn't matter, matching is done by (property, hasObject_name-
# substring, hasObject_type).
GOLD = {
    "TGS07JoshFarleyTranscript.docx.intro.txt": {
        "public_name": "Josh Farley",
        "relationships": [
            {
                "property": "thinkr:hasPersonalRelationship",
                "hasObject_name": "University of Vermont",
                "hasObject_type": "thinkr:AcademicInstitution",
            },
            {
                "property": "thinkr:hasPersonalRelationship",
                "hasObject_name": "International Society for Ecological Economics",
                "hasObject_type": "thinkr:Organization",
            },
        ],
    },
    "TGS179MalinPinskyTranscript.intro.txt": {
        "public_name": "Malin Pinsky",
        "relationships": [
            {
                "property": "thinkr:hasPersonalRelationship",
                "hasObject_name": "University of California Santa Cruz",
                "hasObject_type": "thinkr:AcademicInstitution",
            },
            {
                "property": "thinkr:hasPersonalRelationship",
                "hasObject_name": "American Association for the Advancement of Science",
                "hasObject_type": "thinkr:Organization",
            },
            {
                "property": "thinkr:hasPersonalRelationship",
                "hasObject_name": "Ecological Society of America",
                "hasObject_type": "thinkr:Organization",
            },
        ],
    },
}


def call_model(client, model, segment_text):
    kwargs = dict(
        model=model,
        max_tokens=1024,
        system=SYSTEM_PROMPT,
        messages=[{"role": "user", "content": segment_text}],
    )
    if model not in MODELS_REJECTING_TEMPERATURE:
        kwargs["temperature"] = 0
    response = client.messages.create(**kwargs)
    return "".join(block.text for block in response.content if block.type == "text")


def extract_yaml(raw_text):
    """Strips markdown code fences if the model added them despite
    instructions not to, then parses. Returns (parsed_dict_or_None, error)."""
    cleaned = re.sub(r'^```(?:yaml)?\s*\n|\n```\s*$', '', raw_text.strip())
    try:
        return yaml.safe_load(cleaned), None
    except yaml.YAMLError as e:
        return None, str(e)


def match_relationship(gold_rel, extracted_rels):
    """Loose match: same property, same hasObject_type, hasObject_name is a
    case-insensitive substring in either direction (handles the model
    abbreviating "University of California Santa Cruz" as "UC Santa Cruz",
    etc. — flagged as a real match, not a strict-equality failure)."""
    gold_name = gold_rel["hasObject_name"].lower()
    for er in extracted_rels:
        if not isinstance(er, dict):
            continue
        er_name = str(er.get("hasObject_name", "")).lower()
        if (
            er.get("property") == gold_rel["property"]
            and er.get("hasObject_type") == gold_rel["hasObject_type"]
            and (gold_name in er_name or er_name in gold_name)
            and er_name
        ):
            return er
    return None


def evaluate_file(client, model, filename):
    path = INTRO_SEGMENTS_DIR / filename
    if not path.exists():
        return {"file": filename, "error": f"segment file not found: {path}"}

    segment_text = path.read_text(errors="replace")
    gold = GOLD[filename]

    raw_output = call_model(client, model, segment_text)
    parsed, parse_error = extract_yaml(raw_output)

    result = {
        "file": filename,
        "model": model,
        "raw_output": raw_output,
        "parse_error": parse_error,
    }

    if parse_error:
        result["yaml_valid"] = False
        return result

    result["yaml_valid"] = True
    persona = (parsed or {}).get("persona", {}) or {}
    extracted_name = persona.get("public_name", "")
    extracted_rels = persona.get("relationships", []) or []
    human_lead = (parsed or {}).get("human_lead", {}) or {}

    result["target_class_correct"] = persona.get("target_class") == "thinkr:Persona"
    result["public_name_extracted"] = extracted_name
    result["public_name_match"] = gold["public_name"].lower() in extracted_name.lower()
    result["human_lead_present"] = bool((human_lead.get("scopeNote") or "").strip())

    matched = []
    missed = []
    for gold_rel in gold["relationships"]:
        m = match_relationship(gold_rel, extracted_rels)
        if m:
            matched.append((gold_rel["hasObject_name"], m))
        else:
            missed.append(gold_rel["hasObject_name"])

    matched_objs = [m for _, m in matched]
    extra = [er.get("hasObject_name", "?") for er in extracted_rels if er not in matched_objs]

    result["gold_count"] = len(gold["relationships"])
    result["matched_count"] = len(matched)
    result["missed"] = missed
    result["extra"] = extra
    result["recall"] = len(matched) / len(gold["relationships"]) if gold["relationships"] else 1.0

    return result


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--model", default=MODEL_FAST,
                         help=f"Model to test (default: {MODEL_FAST}). "
                              f"Temperature is omitted automatically for models in "
                              f"{MODELS_REJECTING_TEMPERATURE}.")
    args = parser.parse_args()

    api_key = os.environ.get("ANTHROPIC_API_KEY")
    if not api_key:
        # Minimal .env loader — avoids adding python-dotenv as a hard runtime
        # dependency for a one-off eval script; requirements.txt already lists
        # python-dotenv for the real pipeline, this is just a fallback.
        env_path = Path(".env")
        if env_path.exists():
            for line in env_path.read_text().splitlines():
                if line.startswith("ANTHROPIC_API_KEY="):
                    api_key = line.split("=", 1)[1].strip()
                    break
    if not api_key:
        print("ERROR: ANTHROPIC_API_KEY not set and no .env found. Aborting.", file=sys.stderr)
        sys.exit(1)

    client = Anthropic(api_key=api_key)

    print(f"Testing model: {args.model}\n")
    all_results = []
    for filename in GOLD:
        print(f"=== {filename} ===")
        result = evaluate_file(client, args.model, filename)
        all_results.append(result)

        if result.get("error"):
            print(f"  ERROR: {result['error']}\n")
            continue
        if not result["yaml_valid"]:
            print(f"  YAML PARSE FAILED: {result['parse_error']}")
            print(f"  Raw output:\n{result['raw_output']}\n")
            continue

        print(f"  target_class: {'thinkr:Persona (correct)' if result['target_class_correct'] else 'WRONG — did not mint Persona'}")
        print(f"  public_name extracted: '{result['public_name_extracted']}' "
              f"({'MATCH' if result['public_name_match'] else 'MISMATCH'})")
        print(f"  relationships: {result['matched_count']}/{result['gold_count']} matched "
              f"(recall={result['recall']:.2f})")
        if result["missed"]:
            print(f"  MISSED: {result['missed']}")
        if result["extra"]:
            print(f"  EXTRA (not in gold — may be real or hallucinated, check manually): {result['extra']}")
        print(f"  human_lead present: {result['human_lead_present']}")
        print()

    valid = [r for r in all_results if r.get("yaml_valid")]
    if valid:
        overall_recall = sum(r["recall"] for r in valid) / len(valid)
        all_persona_class = all(r["target_class_correct"] for r in valid)
        print(f"--- Overall: {len(valid)}/{len(all_results)} files produced valid YAML, "
              f"mean recall {overall_recall:.2f}, "
              f"target_class always Persona: {all_persona_class} ---")
    else:
        print(f"--- 0/{len(all_results)} files produced valid YAML ---")


if __name__ == "__main__":
    main()
